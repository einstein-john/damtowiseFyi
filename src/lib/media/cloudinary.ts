import { v2 as cloudinarySdk, type UploadApiResponse } from "cloudinary";
import type { Env } from "../../config/env.js";

export interface CloudinaryClientConfig {
  cloudName: string;
  apiKey: string;
  apiSecret: string;
  secure: true;
}

export interface UploadedAsset {
  publicId: string;
  version: number;
  format: string;
  width: number;
  height: number;
  bytes: number;
}

export interface UploadOptions {
  folder?: string;
  /** Stable id used to overwrite an asset in place (OG images). */
  publicId?: string;
  /** Omit `unique_filename` only when a stable public id is supplied. */
  uniqueFilename?: boolean;
  invalidate?: boolean;
}

export function configureCloudinary(env: Env): CloudinaryClientConfig {
  const config: CloudinaryClientConfig = {
    cloudName: env.CLOUDINARY_CLOUD_NAME,
    apiKey: env.CLOUDINARY_API_KEY,
    apiSecret: env.CLOUDINARY_API_SECRET,
    secure: true,
  };
  cloudinarySdk.config(config);
  return config;
}

function assertUploadShape(response: UploadApiResponse): UploadedAsset {
  const { public_id: publicId, version, format, width, height, bytes } = response;
  if (!publicId || version === undefined || !format || !width || !height || bytes === undefined) {
    throw new Error("Cloudinary returned an incomplete upload response");
  }
  return { publicId, version, format, width, height, bytes };
}

function runUpload(config: CloudinaryClientConfig, buffer: Buffer, options: Record<string, unknown>): Promise<UploadApiResponse> {
  return new Promise((resolve, reject) => {
    const stream = cloudinarySdk.uploader.upload_stream(
      { ...config, resource_type: "image", ...options },
      (error, result) => {
        if (error) reject(error);
        else if (!result) reject(new Error("Cloudinary upload returned no result"));
        else resolve(result);
      },
    );
    stream.end(buffer);
  });
}

/** Uploads a validated user image; Cloudinary assigns an unpredictable public id. */
export async function uploadImage(
  config: CloudinaryClientConfig,
  buffer: Buffer,
  options: UploadOptions,
): Promise<UploadedAsset> {
  const response = await runUpload(config, buffer, {
    folder: options.folder,
    use_filename: true,
    unique_filename: options.uniqueFilename ?? true,
    overwrite: true,
    invalidate: options.invalidate ?? false,
  });
  return assertUploadShape(response);
}

/**
 * Uploads generated bytes to a fixed, fully-qualified public id. No folder is
 * applied: the id already carries its path, and passing both would double it.
 */
export async function uploadGeneratedImage(
  config: CloudinaryClientConfig,
  buffer: Buffer,
  options: { publicId: string; format: string },
): Promise<UploadedAsset> {
  const response = await runUpload(config, buffer, {
    public_id: options.publicId,
    format: options.format,
    overwrite: true,
    invalidate: true,
    use_filename: false,
    unique_filename: false,
  });
  return assertUploadShape(response);
}

export async function destroyImage(config: CloudinaryClientConfig, publicId: string): Promise<void> {
  await cloudinarySdk.uploader.destroy(publicId, { resource_type: "image", invalidate: true });
}